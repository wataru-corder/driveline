package process_23.copy.copy;

public class Animal {

	private String name;
	private double height;
	public int spped;

	public Animal(String name, double height, int spped) {
		this.name = name;
		this.height = height;
		this.spped = spped;
	}

	public String getName() {
		return name;
	}

	public double getHeight() {
		return height;
	}

	public int getSpped() {
		return spped;
	}

}
